# Violin plot function
plot_violin_gene <- function(
    gene,
    data = full_df,
    smooth_adjust = 1.25,
    TP_subset = NULL,
    Patient_subset = NULL
) {
  stopifnot(gene %in% colnames(data))
  
  df <- data
  
  if (!is.null(TP_subset)) {
    df <- dplyr::filter(df, TP %in% TP_subset)
  }
  
  if (!is.null(Patient_subset)) {
    df <- dplyr::filter(df, Patient %in% Patient_subset)
  }
  
  ggplot(df, aes(x = ID2_TCF7_expression, y = .data[[gene]])) +
    geom_violin(
      aes(fill = ID2_TCF7_expression, color = ID2_TCF7_expression),
      trim = FALSE,
      adjust = smooth_adjust,
      linewidth = 1.1
    ) +
    scale_fill_manual(values = SUBPOP_VIOLIN_FILL, guide = "none") +
    scale_color_manual(values = SUBPOP_OUTLINE, guide = "none") +
    
    ggnewscale::new_scale_fill() +
    ggbeeswarm::geom_quasirandom(
      aes(fill = ID2_TCF7_expression, color = ID2_TCF7_expression),
      shape = 21,
      size = 1.3,
      stroke = 0.35,
      alpha = 0.55,
      width = 0.18
    ) +
    scale_fill_manual(values = SUBPOP_POINTFILL, guide = "none") +
    scale_color_manual(values = SUBPOP_OUTLINE, guide = "none") +
    
    ggnewscale::new_scale_fill() +
    geom_boxplot(
      aes(fill = ID2_TCF7_expression, color = ID2_TCF7_expression),
      width = 0.16,
      outlier.shape = NA,
      linewidth = 0.6,
      median.linewidth = 0.9,
      alpha = 0.7
    ) +
    scale_fill_manual(values = SUBPOP_BOXFILL, guide = "none") +
    scale_color_manual(values = SUBPOP_OUTLINE, guide = "none") +
    
    labs(
      x = "",
      y = paste0(gene, " expression"),
      title = NULL
    ) +
    theme_classic(base_size = 12) +
    theme(
      axis.text.x = element_text(angle = 45, hjust = 1, vjust = 1)
    )
}


# ==============================
# Global + pairwise (unpaired) continuous / discrete / hurdle
# ==============================

safe_p <- function(p) {
  if (is.null(p) || length(p) == 0 || is.na(p)) return(NA_real_)
  max(min(as.numeric(p), 1), 1e-300)
}

hurdle_pvalue <- function(p_cont, p_disc) {
  if (anyNA(c(p_cont, p_disc))) return(NA_real_)
  p_cont <- safe_p(p_cont); p_disc <- safe_p(p_disc)
  stat <- -2 * (log(p_cont) + log(p_disc))
  pchisq(stat, df = 4, lower.tail = FALSE)
}

# ----- Global tests (4 groups) -----

global_continuous_kw <- function(df, gene, group_var = "ID2_TCF7_expression") {
  df_pos <- df %>% dplyr::filter(.data[[gene]] > 0) %>% droplevels()
  if (nrow(df_pos) < 5 || dplyr::n_distinct(df_pos[[group_var]]) < 2) return(NA_real_)
  safe_p(kruskal.test(as.formula(paste0(gene, " ~ ", group_var)), data = df_pos)$p.value)
}

global_discrete_chisq <- function(df, gene, group_var = "ID2_TCF7_expression") {
  df_bin <- df %>% dplyr::mutate(expr = .data[[gene]] > 0) %>% droplevels()
  tab <- table(df_bin$expr, df_bin[[group_var]])
  if (nrow(tab) < 2 || ncol(tab) < 2) return(NA_real_)
  safe_p(suppressWarnings(chisq.test(tab, correct = FALSE)$p.value))
}

# ----- Pairwise tests (2 groups at a time, unpaired) -----

pairwise_continuous_wilcox <- function(df, gene, g1, g2, group_var = "ID2_TCF7_expression") {
  d <- df %>%
    dplyr::filter(.data[[group_var]] %in% c(g1, g2)) %>%
    dplyr::filter(.data[[gene]] > 0) %>%   # continuous = only expressers
    droplevels()
  if (nrow(d) < 5 || dplyr::n_distinct(d[[group_var]]) < 2) return(NA_real_)
  safe_p(wilcox.test(as.formula(paste0(gene, " ~ ", group_var)), data = d)$p.value)
}

pairwise_discrete_fisher <- function(df, gene, g1, g2, group_var = "ID2_TCF7_expression") {
  d <- df %>%
    dplyr::filter(.data[[group_var]] %in% c(g1, g2)) %>%
    dplyr::mutate(expr = .data[[gene]] > 0) %>%
    droplevels()
  tab <- table(d$expr, d[[group_var]])
  if (nrow(tab) < 2 || ncol(tab) < 2) return(NA_real_)
  safe_p(fisher.test(tab)$p.value)
}

# Effect summaries for “driver” label
pairwise_effect_summaries <- function(df, gene, g1, g2, group_var = "ID2_TCF7_expression") {
  d <- df %>% dplyr::filter(.data[[group_var]] %in% c(g1, g2)) %>% droplevels()
  
  # % of "expressing" cells
  prop_tbl <- d %>%
    dplyr::mutate(expr = .data[[gene]] > 0) %>%
    dplyr::group_by(.data[[group_var]]) %>%
    dplyr::summarise(prop_expr = mean(expr), n = dplyr::n(), .groups = "drop")
  
  p1 <- prop_tbl$prop_expr[prop_tbl[[group_var]] == g1]
  p2 <- prop_tbl$prop_expr[prop_tbl[[group_var]] == g2]
  delta_prop <- if (length(p1)==1 && length(p2)==1) (p1 - p2) else NA_real_
  
  # Median among expressers
  med_tbl <- d %>%
    dplyr::filter(.data[[gene]] > 0) %>%
    dplyr::group_by(.data[[group_var]]) %>%
    dplyr::summarise(med_pos = median(.data[[gene]]), n_pos = dplyr::n(), .groups = "drop")
  
  m1 <- med_tbl$med_pos[med_tbl[[group_var]] == g1]
  m2 <- med_tbl$med_pos[med_tbl[[group_var]] == g2]
  delta_med_pos <- if (length(m1)==1 && length(m2)==1) (m1 - m2) else NA_real_
  
  list(delta_prop = delta_prop, delta_med_pos = delta_med_pos)
}

# Main: compute all p-values (global + all 6 pairwise) for one gene
compute_gene_cdh <- function(df, gene, group_var = "ID2_TCF7_expression",
                             adjust_scope = c("within_gene", "none"),
                             include_global = TRUE) {
  adjust_scope <- match.arg(adjust_scope)
  
  lvls <- levels(df[[group_var]])
  lvls <- lvls[lvls %in% unique(as.character(df[[group_var]]))]  # present levels
  pairs <- combn(lvls, 2, simplify = FALSE)
  
  rows <- list()
  
  # --- Global ---
  if (isTRUE(include_global)) {
    pC_global <- global_continuous_kw(df, gene, group_var)
    pD_global <- global_discrete_chisq(df, gene, group_var)
    pH_global <- hurdle_pvalue(pC_global, pD_global)
    
    rows[[length(rows) + 1]] <- data.frame(
      gene = gene,
      contrast = "GLOBAL(4 groups)",
      model = "continuous",
      p = pC_global,
      delta_prop_expr = NA_real_,
      delta_med_pos = NA_real_,
      driver = NA_character_,
      stringsAsFactors = FALSE
    )
    rows[[length(rows) + 1]] <- data.frame(
      gene = gene,
      contrast = "GLOBAL(4 groups)",
      model = "discrete",
      p = pD_global,
      delta_prop_expr = NA_real_,
      delta_med_pos = NA_real_,
      driver = NA_character_,
      stringsAsFactors = FALSE
    )
    rows[[length(rows) + 1]] <- data.frame(
      gene = gene,
      contrast = "GLOBAL(4 groups)",
      model = "hurdle",
      p = pH_global,
      delta_prop_expr = NA_real_,
      delta_med_pos = NA_real_,
      driver = NA_character_,
      stringsAsFactors = FALSE
    )
  }
  
  # --- Pairwise ---
  for (pr in pairs) {
    g1 <- pr[1]; g2 <- pr[2]
    
    pC <- pairwise_continuous_wilcox(df, gene, g1, g2, group_var)
    pD <- pairwise_discrete_fisher(df, gene, g1, g2, group_var)
    pH <- hurdle_pvalue(pC, pD)
    
    eff <- pairwise_effect_summaries(df, gene, g1, g2, group_var)
    
    driver <- dplyr::case_when(
      is.na(pC) | is.na(pD) ~ NA_character_,
      pC < 0.05 & pD >= 0.05 ~ "intensity-driven",
      pD < 0.05 & pC >= 0.05 ~ "frequency-driven",
      pC < 0.05 & pD < 0.05  ~ "both",
      TRUE ~ "neither"
    )
    
    rows[[length(rows) + 1]] <- data.frame(
      gene = gene,
      contrast = paste0(g1, " vs ", g2),
      model = "continuous",
      p = pC,
      delta_prop_expr = eff$delta_prop,
      delta_med_pos = eff$delta_med_pos,
      driver = NA_character_,
      stringsAsFactors = FALSE
    )
    rows[[length(rows) + 1]] <- data.frame(
      gene = gene,
      contrast = paste0(g1, " vs ", g2),
      model = "discrete",
      p = pD,
      delta_prop_expr = NA_real_,
      delta_med_pos = NA_real_,
      driver = NA_character_,
      stringsAsFactors = FALSE
    )
    rows[[length(rows) + 1]] <- data.frame(
      gene = gene,
      contrast = paste0(g1, " vs ", g2),
      model = "hurdle",
      p = pH,
      delta_prop_expr = NA_real_,
      delta_med_pos = NA_real_,
      driver = driver,
      stringsAsFactors = FALSE
    )
  }
  
  out <- do.call(rbind, rows)
  
  if (adjust_scope == "within_gene") {
    
    # default NA
    out$q_model <- NA_real_
    
    # adjust within each model family across pairwise contrasts only
    is_pairwise <- out$contrast != "GLOBAL(4 groups)"
    
    for (m in unique(out$model)) {
      idx <- which(is_pairwise & out$model == m & !is.na(out$p))
      if (length(idx) > 0) {
        out$q_model[idx] <- p.adjust(out$p[idx], method = "BH")
      }
    }
    
  } else {
    out$q_model <- NA_real_
  }
  
  
  out
}





run_gene_report <- function(
    gene,
    data = full_df,
    TP_subset = NULL,
    Patient_subset = NULL,
    p_adjust = "BH",
    save_plot = TRUE,
    plot_dir = "violin_plots",
    dpi = 300,
    width = 6,
    height = 4
) {
  stopifnot(gene %in% colnames(data))
  
  df <- data
  
  if (!is.null(TP_subset)) {
    df <- dplyr::filter(df, TP %in% TP_subset)
  }
  
  if (!is.null(Patient_subset)) {
    df <- dplyr::filter(df, Patient %in% Patient_subset)
  }
  
  tp_label <- if (is.null(TP_subset)) "ALL_TP" else paste(TP_subset, collapse = "_")
  pt_label <- if (is.null(Patient_subset)) "ALL_PATIENTS" else paste(Patient_subset, collapse = "_")
  
  # Build plot (pass through BOTH filters)
  p <- plot_violin_gene(
    gene,
    data = df,
    TP_subset = NULL,          # already filtered
    Patient_subset = NULL      # already filtered
  )
  
  if (isTRUE(save_plot)) {
    if (!dir.exists(plot_dir)) dir.create(plot_dir, recursive = TRUE)
    
    outfile <- file.path(plot_dir, paste0("violin_", gene, "_", tp_label, "_", pt_label, ".tif"))
    
    ggsave(
      filename = outfile,
      plot = p,
      device = "tiff",
      dpi = dpi,
      width = width,
      height = height,
      units = "in",
      compression = "lzw"
    )
    
    cat("Plot saved to:", outfile, "\n")
  }
  
  print(p)
  
  kw <- kruskal.test(
    as.formula(paste0(gene, " ~ ID2_TCF7_expression")),
    data = df
  )
  
  pw <- FSA::dunnTest(
    as.formula(paste0(gene, " ~ ID2_TCF7_expression")),
    data = df,
    method = p_adjust
  )
  
  
  cdh <- compute_gene_cdh(df, gene, adjust_scope = "within_gene", include_global = FALSE)
  
  cat("\nPairwise CONTINUOUS (BH within continuous):\n")
  print(subset(cdh, model == "continuous")[, c("contrast","p","q_model","delta_prop_expr","delta_med_pos")])
  
  cat("\nPairwise DISCRETE (BH within discrete):\n")
  print(subset(cdh, model == "discrete")[, c("contrast","p","q_model")])
  
  cat("\nPairwise HURDLE (BH within hurdle):\n")
  print(subset(cdh, model == "hurdle")[, c("contrast","p","q_model")])
  
  
  
  
  
  
  cat("=============================\n")
  cat("Gene:", gene, "\n")
  cat("TP subset:", tp_label, "\n")
  cat("Patient subset:", pt_label, "\n")
  cat("Plot saved:", if (save_plot) "YES" else "NO", "\n")
  cat("=============================\n\n")
  
  cat("Kruskal–Wallis test:\n")
  print(kw)
  
  cat("\nDunn's test (p.adjust =", p_adjust, "):\n", sep = "")
  print(pw)
  
  invisible(list(
    gene = gene,
    kruskal = kw,
    dunn = pw,
    cdh = cdh
  ))
  
  
  
}

prepare_sig_annotations <- function(cdh_df,
                                    data,
                                    gene,
                                    model = c("continuous", "discrete", "hurdle"),
                                    use_q = TRUE,
                                    alpha = 0.05,
                                    group_var = "ID2_TCF7_expression") {
  
  model <- match.arg(model)
  stat_col <- if (use_q) "q_model" else "p"
  
  ann <- cdh_df %>%
    dplyr::filter(model == !!model) %>%
    dplyr::filter(contrast != "GLOBAL(4 groups)") %>%
    dplyr::filter(!is.na(.data[[stat_col]])) %>%
    dplyr::filter(.data[[stat_col]] < alpha) %>%
    dplyr::mutate(
      group1 = sub(" vs .*", "", contrast),
      group2 = sub(".* vs ", "", contrast)
    )
  
  if (nrow(ann) == 0) return(NULL)
  
  group_levels <- levels(data[[group_var]])
  ann$x1 <- match(ann$group1, group_levels)
  ann$x2 <- match(ann$group2, group_levels)
  
  ann <- ann %>%
    dplyr::arrange(x1, x2) %>%
    dplyr::mutate(
      stack_id = dplyr::row_number(),
      label = dplyr::case_when(
        .data[[stat_col]] < 0.001 ~ "***",
        .data[[stat_col]] < 0.01  ~ "**",
        .data[[stat_col]] < 0.05  ~ "*",
        TRUE ~ "ns"
      )
    )
  
  ann
}


add_sig_brackets <- function(p, ann_df, bracket_color = "black", text_color = "black",
                             tip_length_frac = 0.015, text_size = 3) {
  if (is.null(ann_df) || nrow(ann_df) == 0) return(p)
  
  y_all <- ann_df$y
  y_range <- max(y_all) - min(y_all)
  if (!is.finite(y_range) || y_range == 0) y_range <- 1
  
  tip <- tip_length_frac * y_range
  
  p +
    geom_segment(
      data = ann_df,
      aes(x = x1, xend = x2, y = y, yend = y),
      inherit.aes = FALSE,
      color = bracket_color,
      linewidth = 0.2
    ) +
    geom_segment(
      data = ann_df,
      aes(x = x1, xend = x1, y = y, yend = y - tip),
      inherit.aes = FALSE,
      color = bracket_color,
      linewidth = 0.2
    ) +
    geom_segment(
      data = ann_df,
      aes(x = x2, xend = x2, y = y, yend = y - tip),
      inherit.aes = FALSE,
      color = bracket_color,
      linewidth = 0.2
    ) +
    geom_text(
      data = ann_df,
      aes(x = (x1 + x2) / 2, y = y + tip, label = label),
      inherit.aes = FALSE,
      color = text_color,
      size = text_size
    )
}



plot_violin_all_methods <- function(gene, data = full_df, alpha = 0.05, use_q = TRUE) {
  
  cdh <- compute_gene_cdh(data, gene, adjust_scope = "within_gene", include_global = FALSE)
  p <- plot_violin_gene(gene, data = data)
  
  ann_cont <- prepare_sig_annotations(cdh, data, gene, model = "continuous", use_q = use_q, alpha = alpha)
  ann_disc <- prepare_sig_annotations(cdh, data, gene, model = "discrete",   use_q = use_q, alpha = alpha)
  ann_hurd <- prepare_sig_annotations(cdh, data, gene, model = "hurdle",     use_q = use_q, alpha = alpha)
  
  y_max <- max(data[[gene]], na.rm = TRUE)
  y_min <- min(data[[gene]], na.rm = TRUE)
  y_range <- y_max - y_min
  if (y_range == 0) y_range <- 1
  
  base_y <- y_max + 0.05 * y_range
  step_within <- 0.06 * y_range
  step_between_methods <- 0.10 * y_range
  
  ann_list <- list(
    continuous = ann_cont,
    discrete   = ann_disc,
    hurdle     = ann_hurd
  )
  
  ann_list <- ann_list[!vapply(ann_list, is.null, logical(1))]
  ann_list <- ann_list[vapply(ann_list, nrow, numeric(1)) > 0]
  
  if (length(ann_list) > 0) {
    current_base <- y_max + 0.05 * y_range
    step_within <- 0.08 * y_range
    step_between_methods <- 0.10 * y_range
    
    for (nm in names(ann_list)) {
      ann_list[[nm]]$y <- current_base + (ann_list[[nm]]$stack_id - 1) * step_within
      current_base <- max(ann_list[[nm]]$y) + step_between_methods
    }
  }
  
  if ("continuous" %in% names(ann_list)) {
    p <- add_sig_brackets(p, ann_list[["continuous"]], bracket_color = "purple", text_color = "purple")
  }
  if ("discrete" %in% names(ann_list)) {
    p <- add_sig_brackets(p, ann_list[["discrete"]], bracket_color = "black", text_color = "black")
  }
  if ("hurdle" %in% names(ann_list)) {
    p <- add_sig_brackets(p, ann_list[["hurdle"]], bracket_color = "red", text_color = "red")
  }
  
  p +
    # ggtitle(paste0(gene, " (all pairwise significance methods)")) +
    # labs(subtitle = "Purple = continuous, Black = discrete, Red = hurdle") +
    coord_cartesian(clip = "off") +
    theme(plot.margin = margin(5.5, 40, 5.5, 5.5))
}


