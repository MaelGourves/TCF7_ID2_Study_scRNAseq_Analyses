# Helpers
darken_hex <- function(cols, factor = 0.6) {
  rgb_mat <- grDevices::col2rgb(cols) / 255
  out <- grDevices::rgb(
    rgb_mat[1, ] * factor,
    rgb_mat[2, ] * factor,
    rgb_mat[3, ] * factor
  )
  names(out) <- names(cols)
  out
}

lighten_hex <- function(cols, factor = 0.4) {
  rgb_mat <- grDevices::col2rgb(cols) / 255
  out <- grDevices::rgb(
    rgb_mat[1, ] + (1 - rgb_mat[1, ]) * factor,
    rgb_mat[2, ] + (1 - rgb_mat[2, ]) * factor,
    rgb_mat[3, ] + (1 - rgb_mat[3, ]) * factor
  )
  names(out) <- names(cols)
  out
}

