library(dplyr)
library(tidyr)
library(ggplot2)

full_df <- readRDS("GMM_datasets.rds")
stopifnot("ID2_TCF7_expression" %in% colnames(full_df))

wanted_levels <- c(
  "ID2-TCF7+",
  "ID2+TCF7+",
  "ID2+TCF7-",
  "ID2-TCF7-"
)

# Filter, drop other subpops, then enforce factor order
full_df <- full_df %>%
  dplyr::filter(ID2_TCF7_expression %in% wanted_levels) %>%
  dplyr::mutate(ID2_TCF7_expression = factor(ID2_TCF7_expression, levels = wanted_levels)) %>%
  droplevels()

# Quick check
table(full_df$ID2_TCF7_expression)

# -----------------------------
# SETTINGS
# -----------------------------
TOP_N <- 200                 # It matters if you want to show more genes
TEST <- "kruskal"            # "kruskal" or "anova"
ADJUST <- "BH"               # p.adjust method for ranking
summary_mode <- "mean"       # how to summarize per group for the heatmap: "mean" | "median" | "mean_pos"
scale_mode <- "zscore"       # "zscore" 

# TOP_N <- length(gene_cols) # whole dataset

# -----------------------------
# 1) Identify gene columns
# -----------------------------
anno_cols <- c("Patient", "TP", "TCF7_ID2_TOX_subpop", "ID2_TCF7_expression",
               "ID2_status","TCF7_status","TOX_status","state_binary","Donor")
gene_cols <- setdiff(names(full_df)[sapply(full_df, is.numeric)], anno_cols)

# -----------------------------
# 2) Rank genes by global p-value across 4 groups
# -----------------------------
p_global <- function(gene, df = full_df, group_var = "ID2_TCF7_expression", test = TEST) {
  x <- df[[gene]]
  g <- df[[group_var]]
  
  ok <- is.finite(x) & !is.na(g)
  x <- x[ok]
  g <- droplevels(g[ok])
  
  if (length(x) < 10) return(NA_real_)
  if (dplyr::n_distinct(g) < 2) return(NA_real_)
  if (stats::sd(x) == 0) return(NA_real_)
  
  if (tolower(test) == "anova") {
    # one-way ANOVA without formula strings
    fit <- tryCatch(stats::aov(x ~ g), error = function(e) NULL)
    if (is.null(fit)) return(NA_real_)
    out <- tryCatch(summary(fit)[[1]][["Pr(>F)"]][1], error = function(e) NA_real_)
    return(as.numeric(out))
  } else {
    # Kruskal without formula strings
    out <- tryCatch(stats::kruskal.test(x ~ g)$p.value, error = function(e) NA_real_)
    return(as.numeric(out))
  }
}

# Computation for ~15k genes.
pvals <- vapply(gene_cols, p_global, numeric(1))
qvals <- p.adjust(pvals, method = ADJUST)

rank_tbl <- tibble::tibble(
  gene = gene_cols,
  p = pvals,
  q = qvals
) %>%
  arrange(q, p)

top_genes <- rank_tbl %>%
  dplyr::filter(!is.na(q), q < 0.1) %>% # Customisation q threshold
  dplyr::pull(gene) %>%
  head(TOP_N)

# -----------------------------
# 3) Build gene x subpop matrix for those TOP_N genes
# -----------------------------
summ_fun <- switch(
  summary_mode,
  mean     = function(x) mean(x, na.rm = TRUE),
  median   = function(x) median(x, na.rm = TRUE),
  mean_pos = function(x) { x <- x[x > 0]; if (length(x) == 0) 0 else mean(x) }
)

mat_df <- full_df %>%
  select(ID2_TCF7_expression, all_of(top_genes)) %>%
  pivot_longer(cols = all_of(top_genes), names_to = "gene", values_to = "expr") %>%
  group_by(gene, ID2_TCF7_expression) %>%
  summarise(value = summ_fun(expr), .groups = "drop") %>%
  pivot_wider(names_from = ID2_TCF7_expression, values_from = value)

mat <- as.matrix(mat_df[, -1])
rownames(mat) <- mat_df$gene

# Row-scale for visualization
if (scale_mode == "zscore") {
  mat_use <- t(scale(t(mat)))
  mat_use[is.na(mat_use)] <- 0
} else {
  mat_use <- mat
}

# --- Hierarchical clustering of GENES (rows) ---
row_d <- dist(mat_use, method = "euclidean")      # or "correlation" (see below)
row_hc <- hclust(row_d, method = "complete")      # or "average"
gene_levels <- rownames(mat_use)[row_hc$order]

# Reorder matrix too (optional, but keeps things consistent)
mat_use <- mat_use[gene_levels, , drop = FALSE]



# -----------------------------
# 4) Heatmap plot (ggplot)
# -----------------------------
hm_long <- as.data.frame(mat_use) %>%
  tibble::rownames_to_column("gene") %>%
  tidyr::pivot_longer(-gene, names_to = "subpop", values_to = "value")

hm_long$subpop <- factor(hm_long$subpop, levels = wanted_levels)

hm_long$gene <- factor(hm_long$gene, levels = gene_levels)

p <- ggplot(hm_long, aes(x = subpop, y = gene, fill = value)) +
  geom_tile() +
  scale_fill_gradient2(
    low = "#2166AC", mid = "white", high = "#B2182B",
    midpoint = 0,
    name = if (scale_mode == "zscore") "Z (per gene)" else summary_mode
  ) +
  labs(
    x = NULL, y = NULL,
    title = paste0(
      "Top ", TOP_N, " genes by global ", TEST, " (q=", ADJUST, "), heatmap of ", summary_mode,
      " per subpop (", ifelse(scale_mode == "zscore", "z-scored", "raw"), ")"
    )
  ) +
  theme_classic(base_size = 11) +
  theme(
    axis.text.x = element_text(angle = 35, hjust = 1),
    axis.text.y = element_text(size = 4) # 4-7
  )


p

ggsave("TCF7_ID2_Curated_Heatmap_q0-1.svg",
       p, device = "tiff", dpi = 300,
       width = 9, height = 14, units = "in", compression = "lzw")


# Optional: Ranked list
head(rank_tbl, 20)

# ==============================================================================
# EXPORT .csv
# ==============================================================================

# Means used before z-scoring
mean_df <- mat_df %>%
  rename_with(~ paste0("mean_", .x), -gene)

# Z-scores actually plotted
zscore_df <- as.data.frame(mat_use) %>%
  tibble::rownames_to_column("gene") %>%
  rename_with(~ paste0("zscore_", .x), -gene)

# P-values table
pval_df <- rank_tbl %>%
  select(gene, p, q) %>%
  rename(
    kruskal_p = p,
    BH_q = q
  )

# Mergeing
heatmap_export_df <- mean_df %>%
  left_join(zscore_df, by = "gene") %>%
  left_join(pval_df, by = "gene")

# Optional: keep the same gene order as in the heatmap
heatmap_export_df$gene <- factor(heatmap_export_df$gene, levels = gene_levels)
heatmap_export_df <- heatmap_export_df %>%
  arrange(gene) %>%
  mutate(gene = as.character(gene))

# Save
write.csv(heatmap_export_df, "Curated_TCF7_ID2_heatmap_export.csv", row.names = FALSE)

